"""R.I.O.S. 机制层要用的**关卡装置键**与**天桩时间常数**。

## 为什么单独一份

`spec.py` / `mech.py` 往 Go 送规格时需要这些值，但它们原本住在
`battle/devices.py`（413 行，整个装置运行期层）与 `battle/sim.py`（5069 行，
整个原版模拟器）里——**为了三个字符串去 import 一个 413 行的模块**，
就是把 `battle/` 钉在依赖图上。

⇒ 定义搬到这里；`battle/devices.py` 与 `battle/sim.py` 各自从**这里**转出，
所以引擎那边一行不用改，一份定义、两个消费者。

## ⚠ 搬运前逐条读过原文

本项目有过一次教训（`ba47512d`）：`unit.py` 与 `devices.py` 各有一张
**同名不同义**的 `DIRECTIONS`，合并会让 `dict.get` 静默落默认值、把方向弄反。
所以搬常量**先读原文件的实际内容**，不许照名字抄。
这六条都读过：三条是装置 `key` 字符串，三条是秒数/量程，没有重名冲突。

## ⚠ 注释是搬过来的，别删

每一条上面那行写着**为什么是这个值**。例如 `PILE_SUMMON_DELAY = 1.25` 不是
随手取的中值——原文写的是「1~1.5s 的**随机**延迟」，而这个模拟器必须
**同一份作业每次跑出同一结果**，所以取中值不掷骰。删掉注释，下一个人就会
把它"改回更真实"的随机数，而那会让整套对拍失去意义。
"""

