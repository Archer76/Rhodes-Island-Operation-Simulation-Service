package main

import "math"

// 【抵抗】与「可抵抗状态」的时长／触发口径。
//
// 判据出处：PRTS `可抵抗状态` 页（2026-09-19 抓取，原文）：
//
//	「明日方舟中的每个Buff数据都自带一个名为'抵抗耐性'（statusResistable）的属性，
//	  它有三种类型：不可抵抗（默认）、可抵抗和自动识别。」
//	「当一个Buff的'抵抗耐性'被设置为可抵抗时，会根据干员的'可抵抗状态生效时间倍率
//	  （ONE_MINUS_STATUS_RESISTANCE）'数值来加速自身剩余持续时间的流逝速度。」
//	「当前的持续时间流逝速度倍率 = 1 / 可抵抗状态生效时间倍率
//	  状态实际持续时间 = 原持续时间 × 可抵抗状态生效时间倍率」
//	「减半效果为令可抵抗状态生效时间倍率 × 0.5（最终乘算），同名效果取最高」
//	「因其本质为加速特定状态的持续时间流逝速度，因此会令被抵抗的状态**更频繁触发其
//	  定时触发的效果**（例如'每秒受到一次法术伤害'在抵抗的作用下会变为'每0.5秒受到
//	  一次法术伤害'）；**站内标注为固定的触发间隔不会受可抵抗状态生效时间倍率影响**」
//
// ⚠ 最容易写错的一点：抵抗**不是**"把持续时间一次性砍一半"，而是把计时器的**流逝
// 速度**乘以 `1/倍率`。两者对"还剩多久"等价（`t×(1/f)×f = t`），但对**定时触发的
// 效果**完全不等价——每秒结一次的持续伤害在抵抗下变成每 0.5 秒结一次，**总伤害翻倍**。
// 按"砍一半"实现，这一路会静默丢掉，而且丢得看不出来（时长是对的）。
//
// ⚠ 另一条要落到数据上的：页里区分了"定时触发"与"**固定**触发间隔"。后者**不受**
// 影响。所以本文件只给公式，**哪一条是固定间隔是数据问题**，不许在这里一刀切。

// resistNone 是"没有抵抗"时的可抵抗状态生效时间倍率（原值 1.0）。
const resistNone = 1.0

// resistHalf 是「抵抗」这条本身给出的倍率：令生效时间倍率 ×0.5（最终乘算）。
//
// 于是"持续 10 秒的晕眩"在抵抗下实际是 5 秒；同时它的定时触发的效果间隔也减半。
const resistHalf = 0.5

// resistFactor 按「同名效果取最高」合成两个来源的倍率。
//
// 倍率**越小抵抗越强**（1.0 = 没抵抗，0.5 = 减半），所以"取最高"在数值上就是取小。
// 非正值不是合法游戏值（那意味着状态瞬间结束），这里按"没有抵抗"处理——
// 保守方向：宁可让状态按原时长走，也不要让它瞬间消失。
func resistFactor(a, b float64) float64 {
	if a <= 0 {
		a = resistNone
	}
	if b <= 0 {
		b = resistNone
	}
	return math.Min(a, b)
}

// resistedDuration 是「状态实际持续时间」= 原持续时间 × 生效时间倍率。
//
// 同时就是**定时触发效果的间隔**：页里那句"每秒受到一次法术伤害…变为每 0.5 秒"
// 走的就是这个式子。所以本函数有两个消费点，别只接计时器那一头。
func resistedDuration(base, factor float64) float64 {
	if factor <= 0 {
		factor = resistNone
	}
	if base <= 0 {
		return 0
	}
	return base * factor
}

// advanceStatus 按"加速流逝"推进一个状态计时器，返回推进后的剩余秒数。
//
// 没有抵抗（倍率 1.0）时每帧扣 `dt`；倍率 0.5 时每帧扣 `2×dt`
// （页里的例子：「该晕眩Buff将每帧减少 2/30 秒的剩余持续时间，而非原本的 1/30 秒」）。
//
// ⚠ 调用点必须是**逐帧**推进的那一处（主循环里那一串 `math.Max(0, x-dt)`），
// 不是"施加时把时长改小"——后者是上面说的那个错法。
func advanceStatus(left, dt, factor float64) float64 {
	if factor <= 0 {
		factor = resistNone
	}
	return math.Max(0.0, left-dt/factor)
}

// palsyDecayInterval 是「拥有抵抗的单位每 5 秒流失 1 层」在抵抗下的实际间隔。
//
// ⚠ 这一条是**推导**不是引用：PRTS 只写了"每 5 秒流失 1 层"，没有直接写抵抗下的秒数。
// 推导依据是同页那句"加速流逝 ⇒ 更频繁触发定时效果"，照同一式子得 5 × 倍率 = 2.5 秒。
// 口径若被裁定成别的，只改这里。
func palsyDecayInterval(base, factor float64) float64 {
	if base <= 0 {
		base = 5.0
	}
	return resistedDuration(base, factor)
}
